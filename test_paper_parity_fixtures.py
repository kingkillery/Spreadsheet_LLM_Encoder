BOLD = Font(bold=True)


def _bold_row(ws, row, start_col, values):
    for offset, value in enumerate(values):
        cell = ws.cell(row=row, column=start_col + offset, value=value)
        cell.font = BOLD


def _write_rows(ws, start_row, start_col, rows):
    for r_offset, row in enumerate(rows):
        for c_offset, value in enumerate(row):
            ws.cell(row=start_row + r_offset, column=start_col + c_offset, value=value)


def _simple_table():
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Sheet1"
    _bold_row(ws, 1, 1, ["Region", "Revenue", "Cost"])
    _write_rows(ws, 2, 1, [["West", 100, 40], ["East", 120, 55]])
    return wb, {
        "detected_ranges": ["A1:C3"],
        "prompt_contains": ["(Region|", "(Revenue|", "(Cost|"],
        "remap_ranges": ["A1:C3"],
        "anchor_rows_any": [1, 3],
        "anchor_cols_any": ["A", "C"],
    }


