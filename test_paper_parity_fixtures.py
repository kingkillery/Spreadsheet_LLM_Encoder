class TestPaperParityFixtures(unittest.TestCase):
    def test_fixture_suite_has_paper_parity_expectations(self):
        self.assertEqual(10, len(FIXTURES))
        with tempfile.TemporaryDirectory() as tmpdir:
            for name, builder in FIXTURES:
                with self.subTest(name=name):
                    wb, expected = builder()
                    path = os.path.join(tmpdir, f"{name}.xlsx")
                    wb.save(path)

                    loaded = openpyxl.load_workbook(path, data_only=False)
                    detected = [
                        table["full_range"]
                        for table in detect_tables_in_sheet(loaded["Sheet1"])
                    ]
                    for rng in expected["detected_ranges"]:
                        self.assertIn(rng, detected)

                    encoding = spreadsheet_llm_encode(path, k=1, paper_strict=True)
                    sheet = encoding["sheets"]["Sheet1"]
                    rows = set(sheet["structural_anchors"]["rows"])
                    cols = set(sheet["structural_anchors"]["columns"])
                    self.assertTrue(rows.intersection(expected["anchor_rows_any"]))
                    self.assertTrue(cols.intersection(expected["anchor_cols_any"]))

                    prompt = paper_serializers.to_paper_compressed_prompt(
                        sheet, coord_map=sheet["coord_map"]
                    )
                    for token in expected["prompt_contains"]:
                        self.assertIn(token, prompt)

                    for rng in expected["remap_ranges"]:
                        compact = paper_serializers.remap_range(rng, sheet["coord_map"])
                        self.assertIsNotNone(compact, rng)
                        self.assertEqual(
                            rng,
                            paper_serializers.unremap_range(compact, sheet["coord_map"]),
                        )


if __name__ == "__main__":
    unittest.main()
